"""Export the pinned official Misaki Mandarin frontend data, without models.

This exports dictionaries and rules as runtime data; it is not a precomputed
text-to-phoneme cache. Supply a new output directory. Corpus fixtures remain
separate from the runtime dictionary and are generated by official ZHG2P.
"""

from argparse import ArgumentParser
from functools import lru_cache
from importlib import metadata
from pathlib import Path
import hashlib
import json
import shutil

import cn2an
import jieba
import jieba.posseg as posseg
from misaki.zh import ZHG2P
from misaki.zh_frontend import ZH_MAP
from pypinyin import Style
from pypinyin.constants import PHRASES_DICT, PINYIN_DICT
from pypinyin.converter import UltimateConverter

from export_official import MISAKI_REV, verify_checkout


def main():
    parser = ArgumentParser(description=__doc__)
    parser.add_argument("--misaki-source", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    if args.output.exists():
        raise ValueError("output must be a new directory")
    provenance = verify_checkout(
        args.misaki_source,
        MISAKI_REV,
        ["misaki.zh", "misaki.zh_frontend", "misaki.tone_sandhi"],
    )
    g2p = ZHG2P(version="1.1")
    frontend = g2p.frontend
    converter = UltimateConverter(neutral_tone_with_five=True)
    syllables = []
    syllable_ids = {}

    @lru_cache(maxsize=None)
    def reading(character, original):
        initial = converter.convert_style(
            character, original, Style.INITIALS, strict=True
        )
        final = converter.convert_style(
            character, original, Style.FINALS_TONE3, strict=True
        )
        if character == "嗯":
            final = "n2"
        pair = (initial, final)
        if pair not in syllable_ids:
            syllable_ids[pair] = len(syllables)
            syllables.append(pair)
        return syllable_ids[pair]

    words = {}
    for codepoint, values in PINYIN_DICT.items():
        character = chr(codepoint)
        words[character] = [reading(character, values.split(",")[0])]
    for word, values in PHRASES_DICT.items():
        if len(word) != len(values):
            raise ValueError(
                f"misaligned official pronunciation dictionary entry: {word}"
            )
        words[word] = [reading(c, value[0]) for c, value in zip(word, values)]
    args.output.mkdir(parents=True)
    with jieba.get_dict_file() as stream:
        dictionary = stream.read()
    (args.output / "jieba.dict").write_bytes(dictionary)
    payload = dict(
        format="kokoro-misaki-zh-v1",
        source_revision=MISAKI_REV,
        versions={
            p: metadata.version(p)
            for p in ["misaki", "jieba", "pypinyin", "pypinyin-dict", "cn2an"]
        },
        syllables=syllables,
        words=words,
        phoneme_map=ZH_MAP,
        neutral_words=sorted(frontend.tone_modifier.must_neural_tone_words),
        numeric_chars=sorted(w for w in words if len(w) == 1 and w.isnumeric()),
        not_neutral_words=sorted(frontend.tone_modifier.must_not_neural_tone_words),
        must_erhua=sorted(frontend.must_erhua),
        not_erhua=sorted(frontend.not_erhua),
        jieba_sha256=hashlib.sha256(dictionary).hexdigest(),
        source=provenance,
    )
    states = sorted(posseg.trans_P)
    state_ids = {state: i for i, state in enumerate(states)}
    payload["pos_hmm"] = dict(
        states=states,
        start=[posseg.start_P[state] for state in states],
        transitions=[
            {state_ids[target]: prob for target, prob in posseg.trans_P[state].items()}
            for state in states
        ],
        emissions=[posseg.emit_P[state] for state in states],
        char_states={
            c: sorted(state_ids[state] for state in values)
            for c, values in posseg.char_state_tab_P.items()
        },
    )
    (args.output / "frontend.json").write_text(
        json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    )
    samples = [
        "春天来了，院子里的花开了。",
        "银行行长走在长长的街道上。",
        "他重新称了一遍重量，然后把书归还给她。",
        "单先生和解先生来到重庆。",
        "今天是2026年10月27日，价格是123.45元。",
        "一个人不怕，一会儿再去看看小院儿。",
        "你好，我很好。",
        "我想买一把雨伞。",
        "他听一听，又看一看。",
        "桌子上有三个杯子。",
        "小院儿里，老汉儿和媳妇儿正在聊天。",
        "女儿和孙儿都回来了。",
        "纸老虎和蒙古包。",
        "老虎喜欢吃水果。",
        "你不懂，我也不懂。",
        "第一天，一年，一段，一次，一百。",
        "我们慢慢走，想想怎么办。",
        "他把衣服、葡萄、萝卜和豆腐放在桌上。",
        "气温是25℃，概率为12.5%，比例是3/4。",
        "买2-3个苹果，走10-20公里。",
        "《故事》里写着：“你真的要走吗？”",
        "请按Enter继续。",
        "价格是１２３元。",
        "今天是２０２６年１０月２７日。",
        "今年是2０2６年，００２６年，１２年，１年。",
        "比例是１２.５%，还有１２/３４，买１２-１３个。",
        "０１月０２日，温度２５℃，１２３４５６年。",
        "他们来这儿，我们去那儿。",
        "这儿是哪儿？那儿有一只鸟儿。",
    ]
    fixtures = []
    for text in samples:
        normalized = ZHG2P.map_punctuation(cn2an.transform(text, "an2cn"))
        phonemes, _ = g2p(text)
        fixtures.append(
            dict(
                text=text,
                normalized=normalized,
                phonemes=phonemes,
                segmentation=[list(x) for x in posseg.lcut(normalized)],
            )
        )
    (args.output / "fixtures.json").write_text(
        json.dumps(fixtures, ensure_ascii=False, indent=2)
    )
    licenses = args.output / "licenses"
    licenses.mkdir()
    shutil.copyfile(args.misaki_source / "LICENSE", licenses / "misaki-APACHE.txt")
    for package in ["jieba", "pypinyin", "pypinyin-dict", "cn2an"]:
        dist = metadata.distribution(package)
        for item in dist.files or []:
            if "license" in item.name.lower() or item.name.upper().startswith(
                "COPYING"
            ):
                path = Path(dist.locate_file(item))
                if path.is_file():
                    shutil.copyfile(path, licenses / f"{package}-{item.name}")
    print(
        json.dumps(
            dict(
                words=len(words),
                syllables=len(syllables),
                frontend_bytes=(args.output / "frontend.json").stat().st_size,
                jieba_bytes=len(dictionary),
            ),
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
