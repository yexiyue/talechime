"""Package an independently verified frontend export for public distribution.

Development only. Writes a new directory; never uploads or reads credentials.
Run frontend_compare first and supply its complete log.
"""
from argparse import ArgumentParser
from pathlib import Path
import hashlib
import json
import shutil

EXPECTED_VERSIONS = {
    "misaki": "0.9.4", "jieba": "0.42.1", "pypinyin": "0.55.0",
    "pypinyin-dict": "0.9.0", "cn2an": "0.5.24",
}
LICENSES = ["misaki-APACHE.txt", "jieba-LICENSE", "pypinyin-LICENSE.txt",
            "pypinyin-dict-LICENSE", "cn2an-LICENSE"]
NOTICE = """# Kokoro Mandarin frontend data v1

This package contains exported runtime data, not executable Python or acoustic weights.
Original pronunciation and rule behavior: hexgrad/misaki 0.9.4,
revision fba1236595f2d2bf21d414ba6e57d25256afada3 (Apache-2.0).
https://github.com/hexgrad/misaki/tree/fba1236595f2d2bf21d414ba6e57d25256afada3
Misaki zh_frontend.py and tone_sandhi.py adapt PaddleSpeech:
Copyright (c) 2021 PaddlePaddle Authors. All Rights Reserved. Apache-2.0.

The JSON representation and syllable index are generated by TaleChime.
Pronunciation dictionaries, POS-HMM and segmenter data retain their upstream terms:
- jieba 0.42.1, MIT: https://github.com/fxsjy/jieba/tree/v0.42.1
- pypinyin 0.55.0, MIT: https://pypi.org/project/pypinyin/0.55.0/
- pypinyin-dict 0.9.0, MIT: https://pypi.org/project/pypinyin-dict/0.9.0/
- cn2an 0.5.24, MIT: https://pypi.org/project/cn2an/0.5.24/

See licenses/ for the complete license texts. The Apache and MIT terms apply
per source; this package does not replace them with a single license.
The exported runtime data is distinct from the independent 29-case test corpus.
One mixed English case is explicitly unsupported; the remaining 28 cases match
pinned Misaki output. This is frontend validation, not a claim of acoustic quality.
"""


def sha(path):
    with path.open("rb") as f:
        return hashlib.file_digest(f, "sha256").hexdigest()


def main():
    parser = ArgumentParser(description=__doc__)
    parser.add_argument("--export", type=Path, required=True)
    parser.add_argument("--validation-log", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    if args.output.exists():
        raise ValueError("output must be a new directory")
    data = json.loads((args.export / "frontend.json").read_text())
    if data["format"] != "kokoro-misaki-zh-v1" or data["source_revision"] != "fba1236595f2d2bf21d414ba6e57d25256afada3" or data["versions"] != EXPECTED_VERSIONS:
        raise ValueError("unrecognized frontend source or dependency versions")
    if data["jieba_sha256"] != sha(args.export / "jieba.dict"):
        raise ValueError("dictionary digest mismatch")
    if any(item["path"].startswith("/") for item in data["source"].values()):
        raise ValueError("provenance must contain module-relative paths")
    log = args.validation_log.read_text()
    if "29 cases, 0 failures" not in log or sum(line.startswith("PASS ") for line in log.splitlines()) != 28 or sum(line.startswith("EXPLICIT_UNSUPPORTED ") for line in log.splitlines()) != 1:
        raise ValueError("frontend_compare did not validate the complete corpus")
    sources = ["frontend.json", "jieba.dict", "fixtures.json"] + ["licenses/" + name for name in LICENSES]
    # Validate all explicit inputs before producing an uploadable tree.
    for name in sources:
        if not (args.export / name).is_file() or (args.export / name).is_symlink():
            raise ValueError("missing or invalid export file: " + name)
    args.output.mkdir(parents=True)
    for name in sources:
        target = args.output / name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(args.export / name, target)
    (args.output / "NOTICE.md").write_text(NOTICE)
    files = {name: {"bytes": (args.output / name).stat().st_size, "sha256": sha(args.output / name)} for name in [*sources, "NOTICE.md"]}
    manifest = {
        "format": "talechime-kokoro-frontend-v1", "versions": EXPECTED_VERSIONS,
        "source_revision": data["source_revision"], "files": files,
        "generation": {name: sha(Path(__file__).parent / name) for name in ["export_frontend.py", "export_official.py", "package_frontend.py"]},
        "validation": {"cases": 29, "matched": 28, "explicit_unsupported": 1, "failures": 0},
    }
    (args.output / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n")
    print(json.dumps({"files": len(files) + 1, "bytes": sum(p.stat().st_size for p in args.output.rglob("*") if p.is_file())}))


if __name__ == "__main__":
    main()
